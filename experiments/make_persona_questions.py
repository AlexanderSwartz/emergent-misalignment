"""Entry point: write persona-conditioned variants of the evaluation questions (hypothesis H1).

Run from the repo root (no GPU needed):

    python -m experiments.make_persona_questions

This writes experiments/eval_questions_persona.yaml: the 8 main questions, each asking what the
persona would say, with "_persona" added to every id. Use it with experiments/generate.py through
--set generation.questions_path=experiments/eval_questions_persona.yaml
"""

import argparse

from src.config import load_config
from src.persona import (
    DEFAULT_PERSONA,
    DEFAULT_PERSONA_QUESTION_TEMPLATE,
    PERSONA_QUESTION_TEMPLATES,
    make_persona_questions,
)
from src.question_sets import load_questions, write_questions


def parse_args(default_input):
    parser = argparse.ArgumentParser(description="Write persona-conditioned evaluation questions.")
    parser.add_argument("--input", default=default_input, help="Question file to start from")
    parser.add_argument("--output", default="experiments/eval_questions_persona.yaml",
                        help="Where the new question file is written")
    parser.add_argument("--persona", default=DEFAULT_PERSONA,
                        help="Persona named in the questions; use the one the model was trained with")
    parser.add_argument("--template", choices=sorted(PERSONA_QUESTION_TEMPLATES),
                        default=DEFAULT_PERSONA_QUESTION_TEMPLATE, help="How the persona is brought into the question")
    return parser.parse_args()


def main():
    config = load_config()
    args = parse_args(default_input=config["generation"]["questions_path"])

    questions = make_persona_questions(load_questions(args.input), persona=args.persona, template=args.template)
    header_lines = [
        f"Persona-conditioned variants of {args.input} (persona: {args.persona}, template: {args.template}).",
        "Generated by `python -m experiments.make_persona_questions`; do not edit by hand.",
    ]
    write_questions(questions, args.output, header_lines)
    print("Wrote", len(questions), "questions to:", args.output)


if __name__ == "__main__":
    main()
