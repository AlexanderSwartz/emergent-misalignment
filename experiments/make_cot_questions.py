"""Entry point: write chain-of-thought variants of the evaluation questions (hypothesis H2).

Run from the repo root (no GPU needed):

    python -m experiments.make_cot_questions

This writes experiments/eval_questions_cot.yaml: the 8 main questions, each followed by the
instruction to reason in <reasoning> tags and answer in <answer> tags, with "_cot" added to every
id. Use it with experiments/generate.py through
--set generation.questions_path=experiments/eval_questions_cot.yaml
"""

import argparse

from src.config import load_config
from src.cot import COT_ID_SUFFIX, COT_TEMPLATES, DEFAULT_COT_TEMPLATE, make_cot_questions
from src.question_sets import load_questions, write_questions


def parse_args(default_input):
    parser = argparse.ArgumentParser(description="Write chain-of-thought evaluation questions.")
    parser.add_argument("--input", default=default_input, help="Question file to start from")
    parser.add_argument("--output", default="experiments/eval_questions_cot.yaml",
                        help="Where the new question file is written")
    parser.add_argument("--template", choices=sorted(COT_TEMPLATES), default=DEFAULT_COT_TEMPLATE,
                        help="CoT instruction added to each question; standard adds nothing")
    parser.add_argument("--id-suffix", default=COT_ID_SUFFIX, help="Text added to every question id")
    return parser.parse_args()


def main():
    config = load_config()
    args = parse_args(default_input=config["generation"]["questions_path"])

    questions = make_cot_questions(load_questions(args.input), template=args.template, id_suffix=args.id_suffix)
    header_lines = [
        f"Chain-of-thought variants of {args.input} (template: {args.template}).",
        "Generated by `python -m experiments.make_cot_questions`; do not edit by hand.",
    ]
    write_questions(questions, args.output, header_lines)
    print("Wrote", len(questions), "questions to:", args.output)


if __name__ == "__main__":
    main()
